"""화면에 보이지 않는 신호. 묵상자의 글이 아니라 앱이 인도자에게 상황을 알리는 말이다.
묵상 기록을 정리할 때는 묵상자의 글로 세지 않는다."""

# AI API는 첫 글이 묵상자 쪽이어야 하므로, 묵상을 열 때 이 신호를 넣는다.
START_SIGNAL = "(묵상자가 본문을 정하고 묵상을 시작했습니다. 1단계부터 인도해 주세요.)"
# 묵상자가 중간에 멈췄다가 돌아왔을 때 넣는다. 인도자의 지시문은 건드리지 않고 사실만 알린다.
RESUME_SIGNAL = "(묵상자가 잠시 멈추었다가 돌아왔습니다. 어디까지 했는지 한두 문장으로 짚어 주고, 멈춘 곳에서 이어서 인도해 주세요.)"
SIGNALS = (START_SIGNAL, RESUME_SIGNAL)

# 묵상을 여는 인도자의 첫 말. AI에게 맡기지 않고 정해 둔다: 늘 짧고, 기다림 없이 바로 뜬다.
OPENING = "기도로 묵상을 시작하겠습니다."
